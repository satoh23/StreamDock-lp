type Highlight = {
  label: string;
  /**
   * 文字列で渡すと「。」ごとに改行する（既定）。
   *
   * ⚠ 文が多いカードは、全部の句点で折ると 4 行 5 行になって逆に読みにくい。
   * そのときは**配列**で渡す。要素 1 つが 1 段落になり、**段落の中は改行しない**
   * （＝どの文をひとまとまりで読ませるかを、書く側が決められる）。
   */
  body: string | string[];
  /** public/images/<name>.* を指す。 */
  asset: {
    name: string;
    width: number;
    height: number;
    alt: string;
    /** 動く素材（<name>.webm / .mp4 ＋ <name>-still.png）か。 */
    video?: boolean;
    /** ダーク用（<name>-dark.*）を用意してあるか。 */
    dark?: boolean;
  };
};

