export function CommentViewer() {
  return (
    <Section
      id="comment-viewer"
      eyebrow="内蔵コメントビューア"
      title={
        <>
          配信に必要な機能を盛り込んだ
          <br />
          高機能コメントビューア
        </>
      }
      lead="別のツールを探して用意しなくても、配信に必要なものはこれ一つで揃います。"
      tinted
    >
      <ul className={styles.grid}>
        {FEATURES.map((feature) => (
          <li key={feature.label} className={styles.card}>
            <Screenshot
              name={feature.name}
              width={feature.width}
              height={feature.height}
              alt={feature.alt}
              dark={feature.dark}
              frame="16 / 10"
            />
            <p className={styles.label}>{feature.label}</p>
          </li>
        ))}

        {/* 並び順は配信の時系列
            （配信中の演出・ガチャ・投げ銭 → 配信後のサマリー → 視聴者の履歴）。 */}
        {HIGHLIGHTS.map((item, index) => (
          <li
            key={item.label}
            className={index % 2 === 1 ? styles.wideReverse : styles.wide}
          >
            <div className={styles.wideCopy}>
              <p className={styles.wideLabel}>{item.label}</p>
              {(Array.isArray(item.body) ? item.body : [item.body]).map(
                (paragraph) => (
                  <p key={paragraph} className={styles.wideBody}>
                    {Array.isArray(item.body) ? (
                      paragraph
                    ) : (
                      <Sentences text={paragraph} />
                    )}
                  </p>
                ),
              )}
            </div>
            <Screenshot
              name={item.asset.name}
              width={item.asset.width}
              height={item.asset.height}
              alt={item.asset.alt}
              video={item.asset.video}
              dark={item.asset.dark}
            />
          </li>
        ))}
      </ul>
    </Section>
  );
}
